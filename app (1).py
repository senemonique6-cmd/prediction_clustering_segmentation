import streamlit as st
import pandas as pd
import joblib

# Configuration
st.set_page_config(
    page_title="DBSCAN - Wheat Seeds",
    page_icon="🌾",
    layout="wide"
)

st.title("🌾 Clustering des grains de blé")
st.subheader("DBSCAN")

st.write(
    "Cette application applique l'algorithme DBSCAN "
    "aux caractéristiques morphologiques des grains de blé."
)

# Chargement du modèle
@st.cache_resource
def load_model():
    return joblib.load("dbscan_wheat.pkl")

dbscan_model = load_model()

# Variables utilisées
features = [
    "area A",
    "perimeter",
    "compactness",
    "length of kernel",
    "width of kernel",
    "asymmetry coefficient",
    "length of kernel groove"
]

# Upload du dataset
uploaded_file = st.file_uploader(
    "📂 Charger le fichier CSV",
    type=["csv"]
)

if uploaded_file is not None:

    df = pd.read_csv(uploaded_file)

    st.success("Dataset chargé avec succès !")

    st.write("### Aperçu du dataset")
    st.dataframe(df, use_container_width=True)

    # Vérification des colonnes
    if all(col in df.columns for col in features):

        X = df[features]

        st.write("### Variables utilisées")
        st.write(features)

        if st.button("🚀 Lancer DBSCAN"):

            # Clustering
            clusters = dbscan_model.fit_predict(X)

            # Ajouter les clusters
            resultats = df.copy()
            resultats["Cluster"] = clusters

            st.success("Clustering terminé !")

            # Résultats
            st.write("### 📊 Résultats")

            st.dataframe(
                resultats,
                use_container_width=True
            )

            # Nombre de clusters
            n_clusters = len(
                set(clusters)
            ) - (1 if -1 in clusters else 0)

            # Nombre de points bruit
            n_bruit = sum(clusters == -1)

            col1, col2 = st.columns(2)

            with col1:
                st.metric(
                    "Nombre de clusters",
                    n_clusters
                )

            with col2:
                st.metric(
                    "Points considérés comme bruit",
                    n_bruit
                )

            # Distribution
            st.write("### 📈 Distribution des clusters")

            distribution = (
                resultats["Cluster"]
                .value_counts()
                .sort_index()
            )

            st.bar_chart(distribution)

            # Télécharger
            csv_resultat = resultats.to_csv(
                index=False
            ).encode("utf-8")

            st.download_button(
                "⬇️ Télécharger les résultats",
                csv_resultat,
                "resultats_dbscan.csv",
                "text/csv"
            )

    else:

        st.error(
            "❌ Les colonnes du fichier ne correspondent "
            "pas aux variables attendues."
        )